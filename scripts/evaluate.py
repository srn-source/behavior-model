"""Score every saved prediction on val and test, against both targets, with one scorer.

Outputs (results/metrics/):
  leaderboard.csv / leaderboard.md   one row per (experiment, target, split)
  leaderboard_by_task.csv            per-task scores on the test split
and reports/figures/leaderboard.png.

Reference rows computed here:
  REF_retest_copy   Setting B: copy the person's answer from the other wave (human retest)
  REF_random        expected score of a uniform random answer

Gap closed (columns gap_closed, gap_ci_lo, gap_ci_hi): mean(model - E0) / mean(retest - E0), the share
of the E0 -> human-retest gap a method closes (0 = E0, 1 = retest). "% of retest" divides the whole
score, so it is inflated by what the population median already earns; this measure is not.

Run after scripts.run_e0 / scripts.run_e4:  python -m scripts.evaluate
"""
from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from scripts import eda_figures  # noqa: F401  (applies the shared plot style)
from scripts.reproduce_retest import expected_random
from src import data
from src import metrics as M
from src.eval import TARGETS, eligible, gap_closed, list_predictions, load_predictions, paired_delta, \
    retest_predictions, score, truth_frames
from src.split import load_split

OUT = data.REPO_ROOT / "results" / "metrics"
FIG = data.REPO_ROOT / "reports" / "figures"
BASELINE = "E0_population_median"
BLUE, ORANGE, AQUA, GRAY, INK, MUTED = "#2a78d6", "#eb6834", "#1baf7a", "#8a8984", "#0b0b0b", "#52514e"


def random_scores(target: str, pids) -> pd.Series:
    truth = truth_frames()[target].loc[list(pids)]
    return M.respondent_scores(expected_random(truth), eligible(pids))


def evaluate_split(split_name: str, pids) -> tuple[list[dict], dict]:
    rows, task_tables = [], {}
    for target in TARGETS:
        retest = score(retest_predictions(target), target, pids)
        base_pred = load_predictions(BASELINE, target)[0] if (BASELINE, target) in list_predictions() else None
        entries = [("REF_retest_copy", retest_predictions(target),
                    dict(label="Human retest (copy other wave's answer)", regime="reference", setting="B"))]
        entries += [(exp, *load_predictions(exp, target)) for exp, t in list_predictions() if t == target]
        for exp_id, pred, meta in entries:
            s = retest if exp_id == "REF_retest_copy" else score(pred, target, pids)
            if s.respondent.empty:
                continue
            mean, lo, hi = M.bootstrap_mean(s.respondent)
            row = dict(
                exp_id=exp_id, label=meta.get("label", exp_id), regime=meta.get("regime", ""),
                setting=meta.get("setting", ""), target=target, split=split_name,
                n_people=int(len(s.respondent)), coverage=round(s.coverage, 4),
                score=mean, ci_lo=lo, ci_hi=hi,
                normalized_vs_retest=mean / retest.respondent.loc[s.respondent.index].mean(),
                caveat=meta.get("caveat", ""),
            )
            if base_pred is not None and exp_id != BASELINE:
                d = paired_delta(pred, base_pred, target, pids)
                row.update(delta_vs_E0=d["delta"], delta_ci_lo=d["ci_lo"], delta_ci_hi=d["ci_hi"],
                           delta_n_people=d["n_people"])
                g = gap_closed(pred, base_pred, retest_predictions(target), target, pids)
                row.update(gap_closed=g["gap_closed"], gap_ci_lo=g["ci_lo"], gap_ci_hi=g["ci_hi"])
            rows.append(row)
            task_tables[(exp_id, target)] = s.task
        r = random_scores(target, pids)
        mean, lo, hi = M.bootstrap_mean(r)
        rows.append(dict(exp_id="REF_random", label="Uniform random answer (expected)", regime="reference",
                         setting="-", target=target, split=split_name, n_people=int(len(r)), coverage=1.0,
                         score=mean, ci_lo=lo, ci_hi=hi,
                         normalized_vs_retest=mean / retest.respondent.loc[r.index].mean(), caveat=""))
    return rows, task_tables


def _pct(x):
    return "" if pd.isna(x) else f"{x:.1%}"


def _delta(r):
    if pd.isna(r.get("delta_vs_E0")):
        return ""
    sig = "excludes 0" if (r.delta_ci_lo > 0 or r.delta_ci_hi < 0) else "includes 0"
    return f"{r.delta_vs_E0 * 100:+.1f} pp [{r.delta_ci_lo * 100:+.1f}, {r.delta_ci_hi * 100:+.1f}] ({sig})"


def _gap(r):
    if pd.isna(r.get("gap_closed")):
        return ""
    return f"{r.gap_closed:+.1%} [{r.gap_ci_lo:+.1%}, {r.gap_ci_hi:+.1%}]"


def write_markdown(lb: pd.DataFrame, by_task: pd.DataFrame):
    lines = [
        "# Leaderboard",
        "",
        "Generated by `python -m scripts.evaluate`. Do not edit by hand.",
        "",
        "Metric: the paper's accuracy (1 − |pred − truth| / range; task-macro per person, mean over people), "
        "95% participant-bootstrap CI. Δ vs E0 is paired, on the cells both methods predicted.",
        "**Primary target: wave 4.** The wave 1–3 target is the paper's framing, used to compare with published LLM numbers.",
        "Regime: *supervised-on-items* methods saw training participants' answers to these items; "
        "*item-zero-shot* methods did not. Comparisons across regimes are not controlled experiments.",
        "Gap closed = mean(method − E0) / mean(retest − E0), paired per person, people resampled jointly: "
        "the share of the E0 → human-retest gap a method closes (0% = E0, 100% = retest). "
        "Unlike % of retest, it does not credit what predicting each item's population answer already earns.",
        "",
    ]
    for split in ("test", "val"):
        for target in TARGETS:
            sub = lb[(lb.split == split) & (lb.target == target)].sort_values("score", ascending=False)
            if sub.empty:
                continue
            tag = " — primary" if (split == "test" and target == "wave4") else ""
            lines += [f"## {split} split, target = {target}{tag}", "",
                      "| Method | Regime | People | Coverage | Score [95% CI] | % of retest | Δ vs E0 [95% CI] | "
                      "Gap closed E0 → retest [95% CI] |",
                      "|---|---|---:|---:|---|---:|---|---|"]
            for _, r in sub.iterrows():
                name = r.label + (f" ⚠️ {r.caveat}" if isinstance(r.caveat, str) and r.caveat else "")
                lines.append(f"| {name} | {r.regime} | {r.n_people} | {_pct(r.coverage)} | "
                             f"{_pct(r.score)} [{_pct(r.ci_lo)}, {_pct(r.ci_hi)}] | {_pct(r.normalized_vs_retest)} | "
                             f"{_delta(r)} | {_gap(r)} |")
            lines.append("")
    if not by_task.empty:
        lines += ["## Per task (test split, target = wave 4)", "",
                  "| Task | " + " | ".join(by_task.columns) + " |", "|---|" + "---:|" * len(by_task.columns)]
        for task, r in by_task.iterrows():
            lines.append(f"| {task} | " + " | ".join(_pct(v) for v in r.values) + " |")
        lines.append("")
    (OUT / "leaderboard.md").write_text("\n".join(lines))


def plot(lb: pd.DataFrame):
    sub = lb[lb.split == "test"]
    fig, axes = plt.subplots(1, 2, figsize=(14, 0.42 * sub.exp_id.nunique() + 1.8), sharey=True)
    order = (sub[sub.target == "wave4"].sort_values("score").exp_id.tolist())
    labels = sub.drop_duplicates("exp_id").set_index("exp_id").label.reindex(order)
    for ax, target in zip(axes, TARGETS):
        t = sub[sub.target == target].set_index("exp_id").reindex(order)
        y = np.arange(len(order))
        colors = [BLUE if e == "REF_retest_copy" else ORANGE if e == BASELINE else GRAY if e == "REF_random"
                  else AQUA for e in order]
        ax.barh(y, t.score, color=colors, height=0.6)
        ax.errorbar(t.score, y, xerr=[t.score - t.ci_lo, t.ci_hi - t.score], fmt="none", ecolor=INK, lw=1, capsize=2)
        for yi, v, hi in zip(y, t.score, t.ci_hi):
            if not pd.isna(v):
                ax.text(hi + 0.004, yi, f"{v:.1%}", va="center", fontsize=8, color=INK)
        ax.set_xlim(0.55, 0.88)
        ax.set_title(f"Test split, target = {target}" + (" (primary)" if target == "wave4" else " (paper's target)"))
        ax.set_xlabel("Paper metric")
    axes[0].set_yticks(np.arange(len(order)), [s if len(s) <= 58 else s[:56] + "…" for s in labels], fontsize=8)
    fig.text(0.01, -0.02, "Blue = human retest (Setting B reference) · orange = E0 population median (train) · "
             "green = published LLM simulations · grey = random", fontsize=8.5, color=MUTED)
    fig.tight_layout()
    FIG.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG / "leaderboard.png", dpi=160, bbox_inches="tight")
    plt.close(fig)


def main():
    split = load_split()
    rows, tasks = [], {}
    for name in ("val", "test"):
        r, t = evaluate_split(name, split[name])
        rows += r
        if name == "test":
            tasks = t
    lb = pd.DataFrame(rows)
    lb.to_csv(OUT / "leaderboard.csv", index=False, float_format="%.4f")
    by_task = pd.DataFrame({e: s for (e, tg), s in tasks.items() if tg == "wave4"})
    keep = [c for c in ["REF_retest_copy", BASELINE] if c in by_task.columns]
    primary = lb[(lb.split == "test") & (lb.target == "wave4")].set_index("exp_id").score
    e4 = sorted((c for c in by_task.columns if c.startswith("E4_")), key=lambda c: -primary.get(c, 0))
    ours = sorted(c for c in by_task.columns if c not in keep and not c.startswith("E4_"))  # E1, E2, ...
    by_task = by_task[keep + ours + e4]
    by_task.to_csv(OUT / "leaderboard_by_task.csv", float_format="%.4f")
    write_markdown(lb, by_task[keep + ours + e4[:2]])  # markdown: references, our models, 2 best LLM specs
    plot(lb)
    view = lb[lb.split == "test"].sort_values(["target", "score"], ascending=[True, False])
    pd.set_option("display.width", 220)
    print(view[["target", "exp_id", "n_people", "coverage", "score", "ci_lo", "ci_hi", "delta_vs_E0",
                "delta_ci_lo", "delta_ci_hi", "gap_closed"]].round(4).to_string(index=False))


if __name__ == "__main__":
    main()
